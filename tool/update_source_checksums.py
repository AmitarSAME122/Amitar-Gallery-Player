#!/usr/bin/env python3
"""Regenerate the deterministic SHA-256 manifest for tracked project files."""
from __future__ import annotations

import hashlib
import os
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "SHA256SUMS.txt"
EXCLUDED_PARTS = {".git", "__pycache__", ".dart_tool", ".pub", ".pub-cache", "build", "dist"}
EXCLUDED_FILES = {
    "SHA256SUMS.txt",
    "android/gradle/wrapper/gradle-wrapper.jar",  # downloaded and SHA-256 verified during bootstrap
    "android/local.properties",  # machine-local Android SDK location; generated by Flutter
    "android/key.properties",  # publisher signing credentials
}


BINARY_SUFFIXES = {".png", ".pdf", ".ico", ".jpg", ".jpeg", ".zip", ".aab", ".apk", ".exe", ".dmg", ".deb"}


def digest(path: Path) -> str:
    """Hash canonical source bytes, independent of CRLF/LF checkout settings."""
    content = path.read_bytes()
    if path.suffix.lower() not in BINARY_SUFFIXES and not path.name.endswith(".tar.gz"):
        content = content.replace(b"\r\n", b"\n")
    return hashlib.sha256(content).hexdigest()


def tracked_project_paths() -> list[Path]:
    """Use Git's index so ignored machine-local files never enter the manifest.

    A source archive has no .git directory. In that case, fall back to a bounded
    project-tree walk with explicit generated/local exclusions.
    """
    try:
        result = subprocess.run(
            ["git", "ls-files", "-z"],
            cwd=ROOT,
            capture_output=True,
            check=False,
        )
    except OSError:
        result = None

    if result is not None and result.returncode == 0 and result.stdout:
        relative_paths = [Path(os.fsdecode(item)) for item in result.stdout.split(b"\0") if item]
    else:
        relative_paths = [path.relative_to(ROOT) for path in ROOT.rglob("*") if path.is_file()]

    selected: list[Path] = []
    for relative in relative_paths:
        normalized = relative.as_posix()
        if normalized in EXCLUDED_FILES:
            continue
        if any(part in EXCLUDED_PARTS for part in relative.parts):
            continue
        absolute = ROOT / relative
        if absolute.is_file():
            selected.append(relative)
    return sorted(set(selected), key=lambda path: path.as_posix())


def main() -> int:
    lines = [
        f"{digest(ROOT / relative)}  {relative.as_posix()}"
        for relative in tracked_project_paths()
    ]
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(lines)} SHA-256 entries to {MANIFEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
